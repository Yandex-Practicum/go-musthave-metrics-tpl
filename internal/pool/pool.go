// Package pool предоставляет типобезопасный пул повторно используемых
// объектов поверх sync.Pool. Он предназначен для «тяжёлых» объектов,
// которые дорого создавать заново: перед возвратом объекта в пул его
// состояние сбрасывается методом Reset, поэтому Get всегда выдаёт
// «чистый» экземпляр.
package pool

import "sync"

// Resetable ограничивает параметр пула типами, умеющими сбрасывать своё
// состояние методом Reset. Обычно это указатель на структуру, для
// которой сгенерирован (или написан вручную) метод Reset.
type Resetable interface {
	Reset()
}

// Pool — обёртка над sync.Pool для повторного использования объектов
// одного конкретного типа T.
type Pool[T Resetable] struct {
	pool sync.Pool
}

// New создаёт и возвращает пул. Функция newFn используется для создания
// новых объектов, когда пул пуст.
func New[T Resetable](newFn func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any { return newFn() },
		},
	}
}

// Get возвращает объект из пула. Если пул пуст, создаётся новый объект с
// помощью функции, переданной в New.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает состояние объекта методом Reset и возвращает его в пул
// для повторного использования.
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.pool.Put(v)
}
